package com.psiwray.organization.terminal_window_gui.widget

/**
 * Border line style for panels and separators.
 *
 * Heavy lines are reserved for v1.1.
 *
 * @since 1.0.0
 */
public enum class BoxStyle {
    /** Single-line border. @since 1.0.0 */
    SINGLE,

    /** Double-line border. @since 1.0.0 */
    DOUBLE,

    /** Rounded corner border with single-line edges. @since 1.0.0 */
    ROUNDED,
}
