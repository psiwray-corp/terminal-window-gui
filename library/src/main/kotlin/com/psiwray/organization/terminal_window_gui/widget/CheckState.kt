package com.psiwray.organization.terminal_window_gui.widget

/**
 * Three-state checkbox value.
 *
 * @since 1.0.0
 */
public enum class CheckState {
    /** Not checked. @since 1.0.0 */
    UNCHECKED,

    /** Checked. @since 1.0.0 */
    CHECKED,

    /** Mixed or partial selection. @since 1.0.0 */
    INDETERMINATE,
}
